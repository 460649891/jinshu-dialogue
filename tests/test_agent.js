'use strict';
const assert = require('node:assert/strict');
const { classifyRender } = require('../src/agent.js');
const { DialogueTracker } = require('../src/agent.js');
// Actual dialogue samples and actual inventory/menu draws captured in this build.
assert.equal(classifyRender(0x3cfef, [25,5,640,480]), 'speaker');
assert.equal(classifyRender(0x3d045, [24,5,640,480]), null, 'Ignore the second shadow pass');
assert.equal(classifyRender(0x3cbe0, [0,0,490,76]), 'text');
assert.equal(classifyRender(0x3cbe0, [0,0,490,54]), 'text');
assert.equal(classifyRender(0x3cbe0, [5,3,449,79]), null, 'Inventory descriptions are not dialogue');
assert.equal(classifyRender(0x3d336, [400,162,640,480]), null, 'Menu values are not dialogue');
assert.equal(classifyRender(0x3cfef, [120,80,640,480]), null, 'Names elsewhere in UI are not speakers');
console.log('7 native render classification checks passed.');

assert.equal(typeof DialogueTracker, 'function');
const tracker = new DialogueTracker();
tracker.begin(1, 'box');
tracker.name(1, [65]);
assert.deepEqual(tracker.body(1, [66]), { sequence:1, speaker:[65], text:[66] });
assert.equal(tracker.body(1, [66]), null, 'Redrawing one invocation must not duplicate it');
tracker.end(1);
tracker.begin(1, 'box');
tracker.name(1, [65]);
assert.deepEqual(tracker.body(1, [66]), { sequence:2, speaker:[65], text:[66] }, 'A later identical dialogue is real');
tracker.end(1);
tracker.begin(1, 'box');
assert.deepEqual(tracker.body(1, [66]).speaker, [], 'A nameless dialogue must not inherit the last speaker');
tracker.begin(1, 'nested');
tracker.name(1, [67]);
assert.equal(tracker.current(1).owner, 'nested');
tracker.end(1);
assert.equal(tracker.current(1).owner, 'box');
tracker.end(1);
assert.equal(tracker.body(1, [66]), null, 'Ignore rendering outside a dialogue invocation');
tracker.begin(2, 'other');
assert.equal(tracker.current(1), null, 'Thread state is isolated');
assert.equal(tracker.body(2, []), null);
assert.notEqual(tracker.body(2, [66]), null, 'An empty render must not consume the dialogue');
console.log('Native dialogue lifecycle checks passed.');
